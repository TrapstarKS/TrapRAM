test('changing experience clears server results and ignores an older response', async ({ page }) => {
  await mockApp(page)
  await select(page, 'Orbit')
  await nav(page, 'Servers').click()
  const place = page.getByRole('textbox', { name: 'Experience link or Place ID' })
  await place.fill('2753915549')
  await page.getByRole('button', { name: 'Load servers', exact: true }).click()
  await expect(page.getByText('server-a', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Full', exact: true })).toBeDisabled()
  await page.evaluate(() => { (window as any).__mock.delays['game:servers'] = 700 })
  await page.getByRole('button', { name: 'Load servers', exact: true }).click()
  await place.fill('920587237')
  await expect(page.getByText('server-a', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Join', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Load servers', exact: true }).click()
  await expect(page.getByText('server-a', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Join', exact: true }).click()
  expect((await calls(page, 'launch:many'))[0].args[1]).toEqual({ placeId: 920587237, jobId: 'server-a' })
})

