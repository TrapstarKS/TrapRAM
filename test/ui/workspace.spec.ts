test('system theme follows the OS and error notifications remain until dismissed', async ({ page }) => {
  await mockApp(page)
  await nav(page, 'Settings').click()
  await page.getByRole('button', { name: 'System', exact: true }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.clock.install()
  await page.evaluate(() => (window as any).__mock.emit('toast:warn', 'Could not finish. Try again.'))
  await page.clock.fastForward(10_000)
  await expect(page.getByRole('alert')).toContainText('Could not finish')
  await page.getByRole('button', { name: 'Dismiss', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
})

for (const theme of ['dark', 'light'] as const) {
  for (const width of [1180, 320]) {
    test(`all sections reflow and pass automated accessibility checks: ${theme}, ${width}px`, async ({ page }, testInfo) => {
      await page.setViewportSize({ width, height: 900 })
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      await mockApp(page)
      await nav(page, 'Settings').click()
      await page.getByRole('button', { name: theme === 'dark' ? 'Dark' : 'Light', exact: true }).click()
      await select(page, 'Orbit')
      for (const section of ['Launch', 'Games', 'Servers', 'Private servers', 'Performance', 'Settings']) {
        await nav(page, section).click()
        const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
        expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) })), section).toEqual([])
        const overflow = await page.evaluate(() => [...document.querySelectorAll<HTMLElement>('main, .app-workspace, .main-scroll, .modal')].filter(e => e.offsetWidth && e.scrollWidth > e.clientWidth + 1).map(e => e.className))
        expect(overflow, section).toEqual([])
      }
      await nav(page, 'Launch').click()
      await page.screenshot({ path: testInfo.outputPath(`workspace-${theme}-${width}.png`) })
      expect(errors).toEqual([])
    })
  }
}

