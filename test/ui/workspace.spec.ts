test('dialog keeps keyboard focus, typing does not reset it, Escape returns to trigger', async ({ page }) => {
  await mockApp(page)
  await nav(page, 'Private servers').click()
  const trigger = page.getByRole('button', { name: 'Add link', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Add a private server' })
  await dialog.getByRole('textbox', { name: 'Share link' }).fill('https://www.roblox.com/share?code=test-code&type=Server')
  await expect(dialog.getByRole('textbox', { name: 'Share link' })).toBeFocused()
  await page.evaluate(() => document.getElementById('account-search')?.focus())
  await expect(dialog.getByRole('textbox', { name: 'Share link' })).toBeFocused()
  for (let i = 0; i < 9; i++) {
    await page.keyboard.press('Tab')
    // Native dialogs may give focus to browser chrome, but never to background controls.
    expect(await dialog.evaluate(el => el.contains(document.activeElement) || document.activeElement === document.body)).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

