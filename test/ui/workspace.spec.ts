import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mockApp } from './mock'

const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Sections' }).getByRole('button', { name, exact: true })
const select = (page: Page, name: string) => page.getByRole('checkbox', { name: `Select ${name}`, exact: true }).check()
const calls = (page: Page, channel: string) => page.evaluate(channel => (window as any).__mock.calls.filter((c: any) => c.channel === channel), channel)

test('selection is visible, filter-aware, and cleared after removal and locking', async ({ page }) => {
  await mockApp(page)
  await select(page, 'Orbit')
  await select(page, 'Nova')
  await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search accounts' }).fill('Echo')
  await expect(page.getByText('2 selected outside this filter')).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await page.evaluate(() => {
    const m = (window as any).__mock
    m.data.accounts = m.data.accounts.filter((a: any) => a.userId !== 1)
    m.emit('data:changed', m.data)
  })
  await expect(page.getByText('1 selected', { exact: true })).toBeVisible()
  await nav(page, 'Lock').click()
  await expect(page.getByRole('heading', { name: 'Vault locked' })).toBeVisible()
  await page.getByRole('button', { name: 'Unlock', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Select Nova', exact: true })).not.toBeChecked()
})

