test('a pasted experience URL launches once with only accounts that have sessions', async ({ page }) => {
  await mockApp(page)
  await page.getByRole('checkbox', { name: 'Select all visible accounts' }).check()
  await page.getByRole('textbox', { name: 'Experience', exact: true }).fill('https://www.roblox.com/games/2753915549/Blox-Fruits?foo=123')
  await page.evaluate(() => { (window as any).__mock.delays['launch:many'] = 1200 })
  const launch = page.getByRole('button', { name: 'Launch 2 accounts', exact: true })
  await launch.click()
  await expect(launch).toBeDisabled()
  await nav(page, 'Games').click()
  await expect(page.locator('.game-actions').getByRole('button', { name: 'Launch', exact: true })).toBeDisabled()
  await expect.poll(() => calls(page, 'launch:many')).toHaveLength(1)
  const [call] = await calls(page, 'launch:many')
  expect(call.args).toEqual([[1, 2], { placeId: 2753915549, jobId: undefined }])
})

